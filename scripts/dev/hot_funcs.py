#!/usr/bin/env python3
"""hot_funcs.py <exe> <out dir> <log> [<log> ...]: the hot-code headers, from sampler logs.

147 MB of lifted code, with the hot functions scattered through it, costs cache and TLB
misses on every far call. Run the game with
    PS3_SAMPLE=1 PS3_SAMPLE_SPURS=all PS3_SAMPLE_HOTLIST=1 PS3_SAMPLE_BUSY=1 PS3_SAMPLE_RVAS=8192
in a few scenes, then point this at the logs. It writes hot_ppu.h and the hot_spu files, forced
into the lifted sources (game/CMakeLists.txt): they put the sampled code in .text$ sections, which
the linker sorts by name, hottest group first. Only where the code sits changes.
"""
import bisect, collections, ctypes, ctypes.wintypes as wt, os, re, sys

exe, out, logs = sys.argv[1], sys.argv[2], sys.argv[3:]
d = ctypes.WinDLL("dbghelp.dll")
proc = wt.HANDLE(0x1237)
d.SymSetOptions(0x2)
d.SymInitializeW(proc, ctypes.c_wchar_p(os.path.dirname(os.path.abspath(exe))), False)
BASE = 0x10000000
d.SymLoadModuleExW.restype = ctypes.c_uint64
d.SymLoadModuleExW(proc, None, ctypes.c_wchar_p(os.path.abspath(exe)), None, ctypes.c_uint64(BASE), 0, None, 0)


class SI(ctypes.Structure):
    _fields_ = [("SizeOfStruct", wt.ULONG), ("TypeIndex", wt.ULONG), ("Reserved", ctypes.c_uint64 * 2),
                ("Index", wt.ULONG), ("Size", wt.ULONG), ("ModBase", ctypes.c_uint64), ("Flags", wt.ULONG),
                ("Value", ctypes.c_uint64), ("Address", ctypes.c_uint64), ("Register", wt.ULONG),
                ("Scope", wt.ULONG), ("Tag", wt.ULONG), ("NameLen", wt.ULONG), ("MaxNameLen", wt.ULONG),
                ("Name", ctypes.c_char * 1)]


syms = []
CB = ctypes.WINFUNCTYPE(wt.BOOL, ctypes.POINTER(SI), wt.ULONG, ctypes.c_void_p)


def on_sym(p, size, _):
    s = p.contents
    name = ctypes.string_at(ctypes.addressof(s) + SI.Name.offset, s.NameLen).decode(errors="replace")
    if re.match(r"(func_[0-9A-F]{8}|.*_spu_(func|region)_[0-9A-F]+)$", name):
        syms.append((int(s.Address) - BASE, int(size), name))
    return True


cb = CB(on_sym)
d.SymEnumSymbols.argtypes = [wt.HANDLE, ctypes.c_uint64, ctypes.c_char_p, CB, ctypes.c_void_p]
d.SymEnumSymbols(proc, ctypes.c_uint64(BASE), b"*", cb, None)
syms.sort()
starts = [s[0] for s in syms]
print(len(syms), "lifted functions in the exe,", sum(s[1] for s in syms) // (1 << 20), "MB")

hits = collections.Counter()
for path in logs:
    for line in open(path, errors="replace"):
        m = re.search(r"\[samp\] rva 0x([0-9A-F]{8}) +[\d.]+% \((\d+)\)", line)
        if not m:
            continue
        rva, n = int(m.group(1), 16), int(m.group(2))
        i = bisect.bisect_right(starts, rva + 15) - 1      # the bucket is 16 bytes
        if i >= 0 and rva < syms[i][0] + max(syms[i][1], 16):
            hits[i] += n

size = {i: syms[i][1] for i in hits}
total = sum(hits.values())
order = sorted(hits, key=lambda i: -hits[i])


def write(path, kinds, header, proto):
    picked = [i for i in order if kinds(syms[i][2])]
    grand = sum(hits[i] for i in picked) or 1
    bytes_ = run = 0
    tiers = [[], [], []]
    for i in picked:                 # 0: 80% of the samples, 1: the next 19%, 2: the rest
        run += hits[i]
        tiers[0 if run <= grand * 0.80 else 1 if run <= grand * 0.99 else 2].append(i)
        bytes_ += size[i]
    with open(os.path.join(out, path), "w", newline="\n") as f:
        f.write("/* Generated by scripts/dev/hot_funcs.py: where the hot lifted code sits in the exe.\n"
                " * Delete the lines (or the file's contents) and nothing changes but speed. */\n")
        f.write(header)
        for t, group in enumerate(tiers):
            for i in sorted(group, key=lambda i: syms[i][2]):
                f.write(proto % (syms[i][2], t))
    print(path, len(picked), "functions,", bytes_ // 1024, "KB, tiers",
          [(len(g), sum(size[i] for i in g) // 1024) for g in tiers])


write("hot_ppu.h", lambda n: n.startswith("func_"),
      '#include "ppu_recomp.h"\n', 'void %s(ppu_context* ctx) __attribute__((section(".text$hp%d")));\n')
# SPU functions can be static, so no redeclaring them: their whole module (one source file)
# goes in a section, through a #pragma in a forced header (hot_spu0.h, hot_spu1.h).
mods = collections.Counter()
modsize = collections.Counter()
for i in hits:
    if not syms[i][2].startswith("func_"):
        mods[syms[i][2].split("_spu_")[0]] += hits[i]
for a, sz, n in syms:
    if not n.startswith("func_"):
        modsize[n.split("_spu_")[0]] += sz
grand, run = sum(mods.values()) or 1, 0
tier = {0: [], 1: []}
for m, n in mods.most_common():
    run += n
    if run <= grand * 0.99:
        tier[0 if run <= grand * 0.80 else 1].append(m)
with open(os.path.join(out, "hot_spu_modules.cmake"), "w", newline="\n") as f:
    f.write("# Generated by scripts/dev/hot_funcs.py: lifted SPU modules by how hot they are.\n")
    for t in tier:
        f.write("set(RACACIT_HOT_SPU%d %s)\n" % (t, " ".join(sorted(tier[t]))))
for t in tier:
    with open(os.path.join(out, "hot_spu%d.h" % t), "w", newline="\n") as f:
        f.write('/* Generated by scripts/dev/hot_funcs.py. */\n#pragma clang section text=".text$hs%d"\n' % t)
print("spu modules", {t: (len(tier[t]), sum(modsize[m] for m in tier[t]) // 1024) for t in tier}, "of", len(modsize))
print("samples", total, "of which in lifted code", sum(hits.values()))
