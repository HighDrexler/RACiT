//! controller-icons: writes game/controller_icons.h from the Kenney Input Prompts
//! pictures in assets/controller-icons (CC0, www.kenney.nl).
//!
//! Run from the repository root: `cargo run --release --manifest-path scripts/controller-icons/Cargo.toml`.
//!
//! Each picture is white on clear with its letters cut out. The cut-outs (clear
//! pixels the outside can't reach) are filled dark, so the letters read on any
//! background. The pictures are then stored as a palette of RGBA colours and
//! runs of palette indices (count 1-255, index), row after row.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::fs;

/// The icons in the order of `ControllerIcon` in the header: per family, SDL's
/// inputs 0-22 (buttons by position, 21 / 22 the triggers) and then the stick
/// and d-pad pictures. "" is an input with no picture (its name is drawn).
const XBOX: [&str; 26] = [
    "xbox_button_color_a", "xbox_button_color_b", "xbox_button_color_x", "xbox_button_color_y",
    "xbox_button_view", "xbox_guide", "xbox_button_menu", "xbox_ls", "xbox_rs", "xbox_lb", "xbox_rb",
    "xbox_dpad_up", "xbox_dpad_down", "xbox_dpad_left", "xbox_dpad_right", "xbox_button_share",
    "xbox_elite_paddle_top_right", "xbox_elite_paddle_top_left", "xbox_elite_paddle_bottom_right",
    "xbox_elite_paddle_bottom_left", "", "xbox_lt", "xbox_rt",
    "xbox_stick_l", "xbox_stick_r", "xbox_dpad",
];
const SWITCH: [&str; 26] = [
    "switch_button_b", "switch_button_a", "switch_button_y", "switch_button_x",
    "switch_button_minus", "switch_button_home", "switch_button_plus", "switch_stick_l_press",
    "switch_stick_r_press", "switch_button_l", "switch_button_r",
    "switch_dpad_up", "switch_dpad_down", "switch_dpad_left", "switch_dpad_right", "",
    "switch_button_sr", "switch_button_sl", "switch_button_sl", "switch_button_sr", "",
    "switch_button_zl", "switch_button_zr",
    "switch_stick_l", "switch_stick_r", "switch_dpad",
];
const PLAYSTATION: [&str; 26] = [
    "playstation_button_color_cross", "playstation_button_color_circle", "playstation_button_color_square",
    "playstation_button_color_triangle", "playstation3_button_select", "", "playstation3_button_start",
    "playstation_button_l3", "playstation_button_r3", "playstation_trigger_l1", "playstation_trigger_r1",
    "playstation_dpad_up", "playstation_dpad_down", "playstation_dpad_left", "playstation_dpad_right",
    "playstation5_button_mute", "", "", "", "", "playstation5_touchpad", "playstation_trigger_l2", "playstation_trigger_r2",
    "playstation_stick_l", "playstation_stick_r", "playstation_dpad",
];
const HOLE: [u8; 4] = [24, 24, 28, 255];

fn load(name: &str) -> (u32, u32, Vec<[u8; 4]>) {
    let path = format!("assets/controller-icons/{name}.png");
    let mut dec = png::Decoder::new(std::io::BufReader::new(fs::File::open(&path).unwrap_or_else(|e| panic!("{path}: {e}"))));
    dec.set_transformations(png::Transformations::EXPAND | png::Transformations::ALPHA | png::Transformations::STRIP_16);
    let mut reader = dec.read_info().expect("png header");
    let mut buf = vec![0; reader.output_buffer_size().expect("size")];
    let info = reader.next_frame(&mut buf).expect("png data");
    let (w, h) = (info.width, info.height);
    let ch = info.color_type.samples();
    let mut px = Vec::with_capacity((w * h) as usize);
    for i in 0..(w * h) as usize {
        let s = &buf[i * ch..i * ch + ch];
        px.push(match ch { 4 => [s[0], s[1], s[2], s[3]], 2 => [s[0], s[0], s[0], s[1]], _ => panic!("{path}: {ch} channels") });
    }
    // Fill the cut-outs: clear pixels the border can't reach through clear pixels.
    let clear = |p: &[u8; 4]| p[3] < 128;
    let mut outside = vec![false; px.len()];
    let mut stack: Vec<(u32, u32)> = Vec::new();
    for x in 0..w { stack.push((x, 0)); stack.push((x, h - 1)); }
    for y in 0..h { stack.push((0, y)); stack.push((w - 1, y)); }
    while let Some((x, y)) = stack.pop() {
        let i = (y * w + x) as usize;
        if outside[i] || !clear(&px[i]) { continue; }
        outside[i] = true;
        if x > 0 { stack.push((x - 1, y)); }
        if y > 0 { stack.push((x, y - 1)); }
        if x + 1 < w { stack.push((x + 1, y)); }
        if y + 1 < h { stack.push((x, y + 1)); }
    }
    for (i, p) in px.iter_mut().enumerate() {
        if !outside[i] && p[3] < 255 {
            // A cut-out (or the soft edge round one): the picture's colour over dark.
            let a = p[3] as u32;
            let mut o = HOLE;
            for k in 0..3 { o[k] = ((p[k] as u32 * a + HOLE[k] as u32 * (255 - a)) / 255) as u8; }
            *p = o;
        }
    }
    (w, h, px)
}

fn main() {
    let mut out = String::new();
    out.push_str("/* Generated by scripts/controller-icons from assets/controller-icons (Kenney Input Prompts,\n");
    out.push_str(" * CC0, www.kenney.nl). Do not edit: change the tool or the pictures and run it again.\n");
    out.push_str(" * Each picture: a palette of RGBA colours and runs of (count, palette index), row after row. */\n");
    out.push_str("#pragma once\n#include <stdint.h>\n\n");
    out.push_str("struct ControllerIcon { uint16_t w, h, colours; const uint8_t* palette; const uint8_t* runs; };\n\n");
    let mut names: Vec<&str> = Vec::new();
    for n in XBOX.iter().chain(SWITCH.iter()).chain(PLAYSTATION.iter()) { if !n.is_empty() && !names.contains(n) { names.push(n); } }
    let mut index = HashMap::new();
    for (i, n) in names.iter().enumerate() {
        let (w, h, px) = load(n);
        let mut pal: Vec<[u8; 4]> = Vec::new();
        let mut map: HashMap<[u8; 4], u8> = HashMap::new();
        let mut runs: Vec<u8> = Vec::new();
        let mut cur: Option<(u8, u8)> = None;
        for p in &px {
            let p = if p[3] == 0 { [0, 0, 0, 0] } else { *p };
            let id = *map.entry(p).or_insert_with(|| { pal.push(p); assert!(pal.len() <= 256, "{n}: over 256 colours"); (pal.len() - 1) as u8 });
            cur = match cur {
                Some((c, v)) if v == id && c < 255 => Some((c + 1, v)),
                Some((c, v)) => { runs.extend([c, v]); Some((1, id)) }
                None => Some((1, id)),
            };
        }
        if let Some((c, v)) = cur { runs.extend([c, v]); }
        let _ = write!(out, "static const uint8_t kIconPal{i}[] = {{");
        for c in &pal { let _ = write!(out, "{},{},{},{},", c[0], c[1], c[2], c[3]); }
        let _ = write!(out, "}};\nstatic const uint8_t kIconRuns{i}[] = {{ /* {n} */");
        for (j, b) in runs.iter().enumerate() { if j % 32 == 0 { out.push('\n'); } let _ = write!(out, "{b},"); }
        out.push_str("\n};\n");
        index.insert(*n, (i, w, h, pal.len()));
    }
    out.push_str("\nstatic const ControllerIcon kControllerIcons[] = {\n");
    for (i, n) in names.iter().enumerate() {
        let (_, w, h, c) = index[n];
        let _ = writeln!(out, "    {{ {w}, {h}, {c}, kIconPal{i}, kIconRuns{i} }},   /* {i} {n} */");
    }
    out.push_str("};\n\n/* Per family (0 Xbox, 1 Switch, 2 PlayStation): SDL input 0-22, then 23 left stick, 24 right stick,\n * 25 d-pad; -1 for none (the input's name is drawn instead). */\n");
    out.push_str("static const int8_t kControllerIconFor[3][26] = {\n");
    for fam in [&XBOX, &SWITCH, &PLAYSTATION] {
        out.push_str("    {");
        for n in fam.iter() { let _ = write!(out, " {},", if n.is_empty() { -1 } else { index[n].0 as i64 }); }
        out.push_str(" },\n");
    }
    out.push_str("};\n");
    fs::write("game/controller_icons.h", out).expect("write game/controller_icons.h");
    eprintln!("game/controller_icons.h: {} pictures", names.len());
}
