#!/usr/bin/env python3
"""Lift raw SPURS policy modules embedded in the PPU EBOOT.

SPURS policy modules (PMs) are raw SPU code, not ELF files, so
extract_spu_images.py misses them. cellSpurs loads a PM at LS 0xA00 and finds
its lifted code by an FNV-1a-64 fingerprint over the raw PM bytes
(spu_workload_fingerprint over sizePm). This script:

  1. slices each PM out of the EBOOT by guest address + size (from the boot log's
     "AddWorkload(wid=N, pm=0x..., size=...)" lines),
  2. wraps it as an SPU ELF at base 0xA00 and lifts it with a unique prefix,
  3. writes game/spu/policy_modules.c, registering each lift under the same
     fingerprint the runtime computes.

Usage: scripts/lift_policy_modules.py input/EBOOT.ELF
"""
import json, os, struct, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PS3R = os.path.join(ROOT, "tools", "ps3recomp", "tools")
PM_BASE = 0xA00
IMAGE_ID_BASE = 100   # clear of build_spu_workloads' 1..N

# name, guest address, size  (from boot log AddWorkload lines)
MODULES = [
    ("pm_wwsjob", 0x00C17B00, 11520),   # "Wws_Job" SPURS job manager
    ("pm_igpm",   0x00AD9500, 560),     # Insomniac "igPm"
]


def fnv1a64(data):
    # Must match runtime/spu/spu_workload.c exactly. Its offset basis is
    # 1469598103934665603 -- NOT the standard FNV-1a 14695981039346656037.
    h = 1469598103934665603
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def read_guest(elf_path, addr, size):
    d = open(elf_path, "rb").read()
    phoff, = struct.unpack(">Q", d[0x20:0x28])
    phentsize, phnum = struct.unpack(">HH", d[0x36:0x3A])
    for i in range(phnum):
        p = d[phoff + i * phentsize: phoff + (i + 1) * phentsize]
        ptype, _, off, vaddr, _, filesz, _, _ = struct.unpack(">IIQQQQQQ", p)
        if ptype == 1 and vaddr <= addr and addr + size <= vaddr + filesz:
            return d[off + addr - vaddr: off + addr - vaddr + size]
    sys.exit(f"0x{addr:X}+{size} is not inside a loaded segment")


def main():
    elf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "input", "EBOOT.ELF")
    out_raw = os.path.join(ROOT, "out", "policy_modules")
    spu_dir = os.path.join(ROOT, "game", "spu")
    os.makedirs(out_raw, exist_ok=True)
    regs, decls, manifest = [], [], []
    for n, (name, addr, size) in enumerate(MODULES):
        raw = read_guest(elf, addr, size)
        fp = fnv1a64(raw)
        bin_p = os.path.join(out_raw, name + ".bin")
        elf_p = os.path.join(out_raw, name + ".elf")
        open(bin_p, "wb").write(raw)
        subprocess.run([sys.executable, "-I", os.path.join(PS3R, "wrap_spu_elf.py"), bin_p,
                        "--out", elf_p, "--base", hex(PM_BASE), "--entry", hex(PM_BASE)], check=True)
        dst = os.path.join(spu_dir, name)
        os.makedirs(dst, exist_ok=True)
        prefix = name + "_"
        r = subprocess.run([sys.executable, "-I", os.path.join(PS3R, "spu_lifter.py"),
                            "--auto-functions", elf_p, "--base", hex(PM_BASE),
                            "--symbol-prefix", prefix, "--output", dst],
                           capture_output=True, text=True)
        log = r.stdout + r.stderr
        open(os.path.join(out_raw, name + ".lift.log"), "w").write(log)
        if r.returncode:
            sys.exit(f"{name}: lifter failed, see {name}.lift.log")
        # bare includes, as build_spu_workloads does
        c = os.path.join(dst, "spu_recomp.c")
        src = open(c).read()
        for h in ("spu_context.h", "spu_helpers.h"):
            src = src.replace(f'"../../runtime/spu/{h}"', f'"{h}"')
        open(c, "w").write(src)
        img = IMAGE_ID_BASE + n
        entry = f"{prefix}spu_func_{PM_BASE:08X}"
        decls += [f"extern void {entry}(spu_context*);",
                  f"extern void {prefix}spu_recomp_register(void);"]
        regs.append(f'    spu_begin_image({img}); {prefix}spu_recomp_register();\n'
                    f'    spu_workload_register_img(0x{fp:016X}ULL, {entry}, {img}, "{name}");')
        manifest.append(dict(name=name, addr=hex(addr), size=size, fp=f"0x{fp:016X}", image=img))
        print(f"{name}: 0x{addr:X} size {size} fp 0x{fp:016X} -> {dst}  [{log.strip().splitlines()[-1] if log.strip() else ''}]")
    with open(os.path.join(spu_dir, "policy_modules.c"), "w") as f:
        f.write("/* Generated by scripts/lift_policy_modules.py -- raw SPURS policy modules. */\n"
                '#include "spu_workload.h"\n\nextern void spu_begin_image(int image_id);\n\n'
                + "\n".join(decls) + "\n\nvoid racacit_pm_register_all(void)\n{\n"
                + "\n".join(regs) + "\n    spu_begin_image(0);\n}\n\n"
                "__attribute__((constructor)) static void racacit_pm_register_ctor(void)\n"
                "{\n    racacit_pm_register_all();\n}\n")
    json.dump(manifest, open(os.path.join(out_raw, "manifest.json"), "w"), indent=2)


if __name__ == "__main__":
    main()
